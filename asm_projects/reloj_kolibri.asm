BITS 32
ORG 0

; ============================================================
; RELOJ LOCAL - KolibriOS + NASM
; ============================================================
;
; Programa BINARIO para KolibriOS
;
; Muestra una ventana con:
;
;        RELOJ LOCAL
;
;        HH:MM:SS
;
; Actualización cada segundo.
;
; ============================================================


; ============================================================
; CABECERA MENUET01 / KOLIBRIOS
; ============================================================

db 'MENUET01'

dd 1
dd start
dd image_end
dd memory_end
dd stack_top
dd 0
dd 0


; ============================================================
; DATOS
; ============================================================

window_title:
    db 'RELOJ LOCAL - KolibriOS',0

label_time:
    db 'HORA LOCAL:',0

time_buffer:
    db '00:00:00',0


hours:
    db 0

minutes:
    db 0

seconds:
    db 0


; ============================================================
; INICIO
; ============================================================

start:

main_loop:

    ; --------------------------------------------------------
    ; Dibujar ventana
    ; --------------------------------------------------------

    call draw_window


    ; --------------------------------------------------------
    ; Esperar aproximadamente 1 segundo
    ;
    ; KolibriOS:
    ; EAX = 5
    ; EBX = tiempo en centésimas de segundo
    ; --------------------------------------------------------

    mov eax,5
    mov ebx,100
    int 0x40


    jmp main_loop


; ============================================================
; DRAW_WINDOW
; ============================================================

draw_window:

    ; --------------------------------------------------------
    ; Inicio de redibujado
    ; --------------------------------------------------------

    mov eax,12
    mov ebx,1
    int 0x40


    ; --------------------------------------------------------
    ; Crear ventana
    ;
    ; X = 100
    ; Y = 100
    ; WIDTH  = 320
    ; HEIGHT = 160
    ; --------------------------------------------------------

    xor eax,eax

    mov ebx,100*65536 + 320
    mov ecx,100*65536 + 160

    mov edx,0x33FFFFFF

    mov edi,window_title

    int 0x40


    ; --------------------------------------------------------
    ; Texto "HORA LOCAL:"
    ; --------------------------------------------------------

    mov eax,4

    mov ebx,30*65536 + 35

    mov ecx,0x80000000

    mov edx,label_time

    int 0x40


    ; --------------------------------------------------------
    ; Obtener hora
    ; --------------------------------------------------------

    call get_time


    ; --------------------------------------------------------
    ; Mostrar HH:MM:SS
    ; --------------------------------------------------------

    mov eax,4

    mov ebx,95*65536 + 75

    mov ecx,0x80000000

    mov edx,time_buffer

    int 0x40


    ; --------------------------------------------------------
    ; Fin de redibujado
    ; --------------------------------------------------------

    mov eax,12
    mov ebx,2
    int 0x40

    ret


; ============================================================
; GET_TIME
; ============================================================
;
; Para esta primera versión obtenemos la hora del RTC CMOS.
;
; CMOS:
;
;   registro 00h = segundos
;   registro 02h = minutos
;   registro 04h = horas
;
; Los valores RTC normalmente vienen en BCD.
;
; ============================================================

get_time:

    ; --------------------------------------------------------
    ; SEGUNDOS
    ; --------------------------------------------------------

    mov al,0x00
    out 0x70,al

    in al,0x71

    call bcd_to_binary

    mov [seconds],al


    ; --------------------------------------------------------
    ; MINUTOS
    ; --------------------------------------------------------

    mov al,0x02
    out 0x70,al

    in al,0x71

    call bcd_to_binary

    mov [minutes],al


    ; --------------------------------------------------------
    ; HORAS
    ; --------------------------------------------------------

    mov al,0x04
    out 0x70,al

    in al,0x71

    call bcd_to_binary

    mov [hours],al


    ; --------------------------------------------------------
    ; HH
    ; --------------------------------------------------------

    movzx eax,byte [hours]

    mov edi,time_buffer

    call byte_to_two_digits


    ; --------------------------------------------------------
    ; :
    ; --------------------------------------------------------

    mov byte [edi],':'
    inc edi


    ; --------------------------------------------------------
    ; MM
    ; --------------------------------------------------------

    movzx eax,byte [minutes]

    call byte_to_two_digits


    ; --------------------------------------------------------
    ; :
    ; --------------------------------------------------------

    mov byte [edi],':'
    inc edi


    ; --------------------------------------------------------
    ; SS
    ; --------------------------------------------------------

    movzx eax,byte [seconds]

    call byte_to_two_digits


    ret


; ============================================================
; BCD_TO_BINARY
; ============================================================
;
; Entrada:
;   AL = valor BCD
;
; Salida:
;   AL = valor binario
;
; Ejemplo:
;
;   25h -> 25
;
; ============================================================

bcd_to_binary:

    mov ah,al

    and al,0x0F

    and ah,0xF0

    shr ah,4

    mov dl,ah

    shl ah,1

    shl dl,3

    add ah,dl

    add al,ah

    ret


; ============================================================
; BYTE_TO_TWO_DIGITS
; ============================================================
;
; Entrada:
;
;   EAX = número 0..99
;   EDI = destino
;
; Salida:
;
;   escribe dos caracteres ASCII
;
; ============================================================

byte_to_two_digits:

    xor edx,edx

    mov ebx,10

    div ebx

    add al,'0'

    mov [edi],al

    inc edi

    add dl,'0'

    mov [edi],dl

    inc edi

    ret


; ============================================================
; ESPACIO PARA PILA
; ============================================================

align 4

stack:

    times 4096 db 0

stack_top:


; ============================================================
; FIN DEL PROGRAMA
; ============================================================

image_end:

memory_end:
