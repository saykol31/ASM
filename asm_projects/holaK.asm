; ============================================================
; HOLAK - K++ / KolibriOS
; Prueba gráfica mínima
; ============================================================

BITS 32
ORG 0

; ============================================================
; KOLIBRIOS HEADER
; ============================================================

db 'MENUET01'             ; 0
dd 1                      ; versión
dd START                  ; punto de entrada
dd I_END                  ; fin de imagen
dd MEM                    ; memoria requerida
dd STACKTOP               ; stack
dd 0                      ; parámetros
dd 0                      ; path

; ============================================================
; PROGRAMA
; ============================================================

START:

    ; --------------------------------------------------------
    ; Dibujar ventana por primera vez
    ; --------------------------------------------------------

    call DRAW_WINDOW


; ============================================================
; BUCLE PRINCIPAL DE EVENTOS
; ============================================================

EVENT_LOOP:

    ; Esperar evento
    mov eax,10
    int 0x40

    ; EAX = 1 -> redraw
    cmp eax,1
    je EVENT_REDRAW

    ; EAX = 2 -> teclado
    cmp eax,2
    je EVENT_KEY

    ; EAX = 3 -> botón
    cmp eax,3
    je EVENT_BUTTON

    jmp EVENT_LOOP


; ============================================================
; REDRAW
; ============================================================

EVENT_REDRAW:

    call DRAW_WINDOW

    jmp EVENT_LOOP


; ============================================================
; TECLADO
; ============================================================

EVENT_KEY:

    ; Obtener tecla
    mov eax,2
    int 0x40

    jmp EVENT_LOOP


; ============================================================
; BOTÓN
; ============================================================

EVENT_BUTTON:

    ; Obtener ID del botón
    mov eax,17
    int 0x40

    ; AH contiene el número del botón
    ; Botón 1 = cerrar ventana

    cmp ah,1
    jne EVENT_LOOP

    ; --------------------------------------------------------
    ; Salir de KolibriOS
    ; --------------------------------------------------------

    mov eax,-1
    int 0x40


; ============================================================
; DIBUJAR VENTANA
; ============================================================

DRAW_WINDOW:

    ; --------------------------------------------------------
    ; Comenzar redraw
    ; --------------------------------------------------------

    mov eax,12
    mov ebx,1
    int 0x40


    ; --------------------------------------------------------
    ; Crear ventana
    ;
    ; X      = 100
    ; Y      = 100
    ; WIDTH  = 400
    ; HEIGHT = 180
    ; --------------------------------------------------------

    mov eax,0

    mov ebx,(100 << 16) + 400

    mov ecx,(100 << 16) + 180

    ; Color área de trabajo
    mov edx,0x14FFFFFF

    ; Color barra/título
    mov esi,0x808899FF

    ; Título
    mov edi,TITLE

    int 0x40


    ; --------------------------------------------------------
    ; Imprimir texto
    ; --------------------------------------------------------

    mov eax,4

    ; Posición:
    ; X = 35
    ; Y = 40

    mov ebx,(40 << 16) + 35

    ; Color del texto
    mov ecx,0x80000000

    ; Dirección del texto
    mov edx,TEXT

    ; Tamaño
    mov esi,40

    int 0x40


    ; --------------------------------------------------------
    ; Segundo texto
    ; --------------------------------------------------------

    mov eax,4

    mov ebx,(70 << 16) + 35

    mov ecx,0x80000000

    mov edx,TEXT2

    mov esi,40

    int 0x40


    ; --------------------------------------------------------
    ; Finalizar redraw
    ; --------------------------------------------------------

    mov eax,12
    mov ebx,2
    int 0x40

    ret


; ============================================================
; DATOS
; ============================================================

TITLE:

    db 'HOLAK - K++ / KolibriOS',0


TEXT:

    db 'HOLA DESDE K++',0


TEXT2:

    db 'KolibriOS GUI funcionando',0


; ============================================================
; FIN DE LA IMAGEN
; ============================================================

I_END:


; ============================================================
; ESPACIO PARA STACK
; ============================================================

times 4096 db 0


; ============================================================
; STACK
; ============================================================

align 16

STACKTOP:


; ============================================================
; MEMORIA DISPONIBLE
; ============================================================

MEM:
